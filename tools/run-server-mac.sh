#!/usr/bin/env bash
# Run the server (crates/server) on **macOS**, in the foreground, with a
# project-local runtime directory — nothing under /etc or /var.
#
# This is the macOS script on purpose. The server is developed and run on a Mac:
# audio arrives over UDP from a node (or from this machine's own device through
# CoreAudio), the recogniser is the Apple sidecar, and the Portal is served from
# web/dist. A Pi runs the same binary from systemd instead; see
# deployment/systemd/steno-monitor.service and docs/operations/2026-10-29-pi-deploy.md.
#
# The runtime directory is `<repo>/var` (git-ignored). It used to be
# `$TMPDIR/steno-server`, which was a mistake once this stopped being a throwaway
# dev run: macOS purges /var/folders/.../T entries it considers unused, and that
# directory holds the recordings and the database.
#
#   tools/run-server-mac.sh                 # net source (a node streams in), loopback HTTP
#   tools/run-server-mac.sh --mic           # open this machine's device instead
#   tools/run-server-mac.sh --lan           # also reachable from a phone on the LAN
#   tools/run-server-mac.sh --stt           # enable streaming speech-to-text
#   tools/run-server-mac.sh --control       # enable start/stop from the Portal
#   tools/run-server-mac.sh --release       # optimised build
#   tools/run-server-mac.sh --reset-config  # regenerate the config file
#   tools/run-server-mac.sh --write-config-only  # write the config and exit (used
#                                           # by refresh-all.sh and dev.sh, so the
#                                           # template lives in exactly one place)
#
# Ctrl-C triggers the documented graceful shutdown (segment closed with
# end_reason=shutdown, database writer drained).
#
# For the edit → build → restart loop use tools/dev.sh instead: it owns the sidecar
# as well and shows the pipeline in the console.

set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
# Project-local by default, overridable for tests and for a second instance.
RUNTIME_DIR="${STENO_RUNTIME_DIR:-$REPO_ROOT/var}"
RUNTIME_DIR="${RUNTIME_DIR%/}"
CONFIG="$RUNTIME_DIR/server.toml"
PORT="${STENO_HTTP_PORT:-8080}"

BIND="127.0.0.1"
SOURCE_KIND="net"
PROFILE="debug"
RESET_CONFIG=0
STT_ENABLED=false
CONTROL_ENABLED=false
WRITE_CONFIG_ONLY=0

usage() {
  local last
  last="$(grep -n '^set -euo pipefail' "${BASH_SOURCE[0]}" | head -1 | cut -d: -f1)"
  sed -n "2,$((last - 2))p" "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'
}

say() { printf '\033[1m==>\033[0m %s\n' "$*"; }
warn() { printf '\033[33mwarning:\033[0m %s\n' "$*" >&2; }
die() { printf '\033[31merror:\033[0m %s\n' "$*" >&2; exit 1; }

while [ $# -gt 0 ]; do
  case "$1" in
    --lan) BIND="0.0.0.0"; shift ;;
    --mic) SOURCE_KIND="alsa"; BIND="127.0.0.1"; shift ;;
    # `--alsa` is what this option was called when the server only ran on Linux.
    # The setting did not change: `source.kind = "alsa"` is the historical value
    # for "open the local device", which on this platform is CoreAudio.
    --alsa)
      warn "--alsa is the old name for --mic (the device here is CoreAudio)"
      SOURCE_KIND="alsa"; BIND="127.0.0.1"; shift ;;
    --stt) STT_ENABLED=true; RESET_CONFIG=1; shift ;;
    --control) CONTROL_ENABLED=true; RESET_CONFIG=1; shift ;;
    --release) PROFILE="release"; shift ;;
    --reset-config) RESET_CONFIG=1; shift ;;
    --write-config-only) WRITE_CONFIG_ONLY=1; shift ;;
    --port) PORT="$2"; shift 2 ;;
    -h|--help) usage; exit 0 ;;
    *) echo "unknown option: $1" >&2; usage >&2; exit 2 ;;
  esac
done

[ "$(uname -s)" = "Darwin" ] || die "this is the macOS runner; on Linux use deployment/systemd/steno-monitor.service (docs/operations/2026-10-29-pi-deploy.md)"

# `control.enabled` is only valid with a loopback bind (see deployment/config.example.toml).
# Refuse here with an explanation instead of letting the server fail validation.
if [ "$CONTROL_ENABLED" = true ] && [ "$BIND" != "127.0.0.1" ]; then
  die "--control requires a loopback bind; drop --lan or drop --control"
fi

mkdir -p "$RUNTIME_DIR"

# The Portal is served from a directory, not embedded in the binary, so a stale
# or missing `web/dist` silently means "API only". Build it on first run.
WEB_DIR="$REPO_ROOT/web/dist"
if [ ! -f "$WEB_DIR/index.html" ]; then
  if command -v npm >/dev/null 2>&1; then
    say "building the Portal (web/dist is missing)"
    (cd "$REPO_ROOT/web" && npm install --silent && npm run build)
  else
    warn "web/dist is missing and npm is not installed; serving the JSON API only"
    WEB_DIR=""
  fi
fi

if [ "$RESET_CONFIG" = 1 ] || [ ! -f "$CONFIG" ]; then
  say "writing $CONFIG"
  mkdir -p "$RUNTIME_DIR/recordings" "$RUNTIME_DIR/db"
  cat >"$CONFIG" <<EOF
# Local development config, generated by tools/run-server-mac.sh.
# Nothing here is a deployment default: deployment/config.example.toml is.

[server]
bind_address = "$BIND"
port = $PORT
http_threads = 2
timezone = ""
web_dir = "$WEB_DIR"

[source]
# "net"  — audio arrives over UDP from a node (tools/dev.sh --with-node, or a Pi)
# "alsa" — this machine opens its own capture device (CoreAudio on macOS)
kind = "$SOURCE_KIND"
bind_address = "0.0.0.0"
port = 8091
device_id = 1
jitter_buffer_ms = 150
idle_timeout_ms = 5000

[audio]
# Short segments make a local run easy to inspect; a real night uses 3600.
device_rate_hz = 16000
device_channels = 1
mono_channel_index = 0
period_ms = 20
buffer_ms = 400
segment_duration_seconds = 60
capture_ring_ms = 500

[storage]
recording_dir = "$RUNTIME_DIR/recordings"
database_path = "$RUNTIME_DIR/db/app.db"
recording_max_bytes = 1073741824
recording_cleanup_target_bytes = 536870912
recording_reserve_bytes = 1048576
retention_check_interval_seconds = 60

[detector]
absolute_floor_dbfs = -55.0

[stt]
# Off by default: it hands audio to another program.
enabled = $STT_ENABLED
mode = "stream"
stream_command = "steno-stt-sidecar"
engine = "apple-speechanalyzer"
locale = "zh-CN"

[control]
# Off by default. Only valid with a loopback bind, which is the default here.
enabled = $CONTROL_ENABLED
server_unit = "steno-monitor"
node_unit = "steno-node"
EOF
fi

if [ "$WRITE_CONFIG_ONLY" = 1 ]; then
  say "wrote $CONFIG"
  exit 0
fi

# Announce what the server will load, not what this script would have written: the
# config may have been generated days ago or edited by hand, and telling someone
# "listening on 8080" while the process uses 9000 sends them to the wrong port.
config_value() { # section key
  awk -v sec="$1" -v key="$2" '
    $0 ~ "^\\[" sec "\\]$" { inside = 1; next }
    /^\[/ { inside = 0 }
    inside && $0 ~ "^" key "[[:space:]]*=" {
      sub(/^[^=]*=[[:space:]]*/, ""); gsub(/"/, ""); print; exit
    }
  ' "$CONFIG" 2>/dev/null
}
EFFECTIVE_BIND="$(config_value server bind_address)"
EFFECTIVE_BIND="${EFFECTIVE_BIND:-$BIND}"
EFFECTIVE_PORT="$(config_value server port)"
EFFECTIVE_PORT="${EFFECTIVE_PORT:-$PORT}"
SOURCE_KIND="$(config_value source kind)"
SOURCE_KIND="${SOURCE_KIND:-net}"
SOURCE_PORT="$(config_value source port)"

say "runtime dir: $RUNTIME_DIR"
say "http: http://$EFFECTIVE_BIND:$EFFECTIVE_PORT/   (API at /api/v1/status)"
if [ "$SOURCE_KIND" = "net" ]; then
  say "waiting for a node on UDP 0.0.0.0:$SOURCE_PORT"
  say "  this machine: tools/dev.sh --with-node      a Pi: tools/deploy-node.sh"
else
  # A microphone *is* a permission on macOS; the on-device recogniser never was.
  # The prompt is attributed to whatever process this binary was started from,
  # which is why running it from a terminal usually just works.
  say "opening the local device (CoreAudio); macOS may ask for microphone access"
fi
if [ "$STT_ENABLED" = true ]; then
  # A missing launcher is not fatal for the recorder, but the Portal would only
  # show "识别器未连接" with no hint, so say it here while the operator is watching.
  if ! command -v steno-stt-sidecar >/dev/null 2>&1; then
    warn "steno-stt-sidecar is not on PATH; the recogniser will report an error"
    warn "  install once:  PREFIX=\$HOME/.local ./apple-stt-sidecar/install.sh"
    warn "  or use tools/dev.sh, which runs the build in this repo without installing"
  fi
fi

cd "$REPO_ROOT"
export STENO_MONITOR_CONFIG="$CONFIG"
export RUST_LOG="${RUST_LOG:-info}"
if [ "$PROFILE" = "release" ]; then
  exec cargo run --release -p steno-server
fi
exec cargo run -p steno-server
